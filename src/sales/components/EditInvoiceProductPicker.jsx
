
import React, { useEffect, useMemo, useRef, useState } from "react";
import {
  Barcode,
  Camera,
  Search,
  Package,
  X,
  Plus,
  List,
} from "lucide-react";
import { getProducts } from "../../productStore.js";
import "./EditInvoiceProductPicker.css";

const normalize = (value) => String(value ?? "").trim().toLowerCase();

function barcodes(product) {
  return [
    product.barcode,
    ...(Array.isArray(product.barcodeAliases) ? product.barcodeAliases : []),
    ...(Array.isArray(product.barcodes) ? product.barcodes : []),
  ].map((value) => String(value ?? "").trim()).filter(Boolean);
}

function reference(product) {
  return String(product.reference ?? product.ref ?? product.sku ?? product.id ?? "");
}

function money(value) {
  return `${(Number(value) || 0).toLocaleString("fr-DZ", {
    maximumFractionDigits: 2,
  })} DA`;
}

export default function EditInvoiceProductPicker({ onSelect, onClose }) {
  const [products, setProducts] = useState([]);
  const [search, setSearch] = useState("");
  const [barcode, setBarcode] = useState("");
  const [showList, setShowList] = useState(true);
  const [cameraOpen, setCameraOpen] = useState(false);
  const [cameraError, setCameraError] = useState("");
  const [notice, setNotice] = useState("");

  const videoRef = useRef(null);
  const streamRef = useRef(null);
  const detectorRef = useRef(null);
  const scanningRef = useRef(false);

  useEffect(() => {
    const inventory = getProducts();
    setProducts(Array.isArray(inventory) ? inventory : []);
  }, []);

  const stopCamera = () => {
    scanningRef.current = false;

    if (streamRef.current) {
      streamRef.current.getTracks().forEach((track) => track.stop());
      streamRef.current = null;
    }

    if (videoRef.current) videoRef.current.srcObject = null;
    setCameraOpen(false);
  };

  useEffect(() => () => {
    scanningRef.current = false;
    streamRef.current?.getTracks().forEach((track) => track.stop());
  }, []);

  const choose = (product) => {
    if (!product) return;
    stopCamera();
    onSelect(product.id);
    onClose();
  };

  const findBarcode = (code) =>
    products.find((product) => barcodes(product).includes(String(code).trim()));

  const submitBarcode = (value) => {
    const code = String(value ?? "").trim();
    if (!code) return;

    const match = findBarcode(code);

    if (match) {
      choose(match);
    } else {
      setSearch(code);
      setShowList(true);
      setNotice("No exact barcode match. Check the search results.");
    }
  };

  const results = useMemo(() => {
    const term = normalize(search);
    if (!term) return products;

    return products.filter((product) =>
      [
        product.name,
        product.id,
        product.sku,
        product.reference,
        product.ref,
        product.category,
        ...barcodes(product),
      ].some((value) => normalize(value).includes(term))
    );
  }, [products, search]);

  const startCamera = async () => {
    setCameraError("");

    if (!navigator.mediaDevices?.getUserMedia) {
      setCameraOpen(true);
      setCameraError("Camera unavailable. Check HTTPS or enter the barcode manually.");
      return;
    }

    if (!("BarcodeDetector" in window)) {
      setCameraOpen(true);
      setCameraError("Automatic barcode scanning is unsupported in this browser. Search manually instead.");
      return;
    }

    try {
      detectorRef.current = new window.BarcodeDetector({
        formats: [
          "ean_13", "ean_8", "upc_a", "upc_e",
          "code_128", "code_39", "itf", "qr_code",
        ],
      });

      const stream = await navigator.mediaDevices.getUserMedia({
        video: { facingMode: { ideal: "environment" } },
        audio: false,
      });

      streamRef.current = stream;
      setCameraOpen(true);

      requestAnimationFrame(async () => {
        if (!videoRef.current) return;

        videoRef.current.srcObject = stream;

        try {
          await videoRef.current.play();
        } catch {
          setCameraError("Could not start the camera preview.");
          return;
        }

        scanningRef.current = true;

        const scan = async () => {
          if (!scanningRef.current || !videoRef.current) return;

          try {
            const codes = await detectorRef.current.detect(videoRef.current);

            if (codes.length && codes[0].rawValue) {
              const value = codes[0].rawValue;
              stopCamera();
              submitBarcode(value);
              return;
            }
          } catch {
            // Continue scanning.
          }

          if (scanningRef.current) requestAnimationFrame(scan);
        };

        requestAnimationFrame(scan);
      });
    } catch {
      setCameraOpen(true);
      setCameraError("Camera permission denied or camera unavailable.");
    }
  };

  return (
    <div className="edit-picker-overlay" role="dialog" aria-modal="true">
      <section className="edit-picker-modal">
        <header className="edit-picker-header">
          <div className="edit-picker-heading-icon"><Package size={21} /></div>
          <div className="edit-picker-heading">
            <h3>Add product to invoice</h3>
            <p>Search by name, barcode or reference.</p>
          </div>
          <button className="edit-picker-close" type="button" onClick={onClose} aria-label="Close">
            <X size={20} />
          </button>
        </header>

        <label className="edit-picker-search">
          <Search size={18} />
          <input
            autoFocus
            value={search}
            onChange={(event) => {
              setSearch(event.target.value);
              setShowList(true);
              setNotice("");
            }}
            placeholder="Product name, reference, SKU or barcode..."
          />
          {search && (
            <button type="button" onClick={() => setSearch("")} aria-label="Clear search">
              <X size={16} />
            </button>
          )}
        </label>

        <form
          className="edit-picker-barcode"
          onSubmit={(event) => {
            event.preventDefault();
            submitBarcode(barcode);
          }}
        >
          <Barcode size={18} />
          <input
            value={barcode}
            onChange={(event) => setBarcode(event.target.value)}
            placeholder="Enter barcode and press Enter"
            aria-label="Barcode"
          />
          <button type="submit">Find</button>
        </form>

        <div className="edit-picker-actions">
          <button className="edit-picker-camera-button" type="button" onClick={startCamera}>
            <Camera size={17} /> Scan with camera
          </button>
          <button
            className="edit-picker-browse-button"
            type="button"
            onClick={() => setShowList((value) => !value)}
          >
            <List size={17} /> {showList ? "Hide product list" : "Browse products"}
          </button>
          <span>{results.length} / {products.length} products</span>
        </div>

        {notice && <p className="edit-picker-notice">{notice}</p>}

        {showList ? (
          <div className="edit-picker-results">
            {results.length === 0 ? (
              <div className="edit-picker-empty">
                <Search size={25} />
                <strong>No matching products</strong>
                <span>Try another name, barcode or reference.</span>
              </div>
            ) : results.map((product) => (
              <button
                type="button"
                className="edit-picker-product"
                key={product.id}
                onClick={() => choose(product)}
              >
                <span className="edit-picker-product-image">
                  {product.image
                    ? <img src={product.image} alt="" />
                    : <Package size={19} />}
                </span>
                <span className="edit-picker-product-info">
                  <strong>{product.name || "Unnamed product"}</strong>
                  <small>Ref: {reference(product) || "—"}</small>
                  {barcodes(product).length > 0 &&
                    <small>Barcode: {barcodes(product)[0]}</small>}
                </span>
                <span className="edit-picker-product-price">
                  <strong>{money(product.price)}</strong>
                  <small>Stock: {Number(product.stock) || 0}</small>
                </span>
                <Plus className="edit-picker-plus" size={19} />
              </button>
            ))}
          </div>
        ) : (
          <div className="edit-picker-empty">
            <List size={26} />
            <strong>Product list hidden</strong>
            <span>Use Browse products to open the inventory list.</span>
          </div>
        )}

        <footer className="edit-picker-footer">
          <span>Select a product to add it to the invoice.</span>
          <button type="button" onClick={onClose}>Cancel</button>
        </footer>

        {cameraOpen && (
          <div className="edit-picker-camera-overlay">
            <div className="edit-picker-camera-dialog">
              <header>
                <div>
                  <h4>Scan product barcode</h4>
                  <p>Point the rear camera at the barcode.</p>
                </div>
                <button type="button" onClick={stopCamera} aria-label="Close scanner">
                  <X size={20} />
                </button>
              </header>
              <video ref={videoRef} playsInline muted className="edit-picker-video" />
              {cameraError && <p className="edit-picker-camera-error">{cameraError}</p>}
              <button className="edit-picker-camera-close" type="button" onClick={stopCamera}>
                Close scanner
              </button>
            </div>
          </div>
        )}
      </section>
    </div>
  );
}
